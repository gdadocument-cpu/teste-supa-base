create table public.site_configuration (
  singleton boolean primary key default true check (singleton),
  max_gda integer not null default 35 check (max_gda between 1 and 200),
  roster_publish_time time without time zone not null default time '20:00:00',
  updated_by_profile_id bigint references public.profiles(id) on delete set null,
  updated_at timestamptz not null default now()
);

