create table public.navigation_links (
  id bigint generated by default as identity primary key,
  external_id uuid not null default gen_random_uuid() unique,
  category text not null check (category in ('LIENS_UTILES', 'INSTRUCTEUR')),
  label text not null check (char_length(btrim(label)) between 1 and 100),
  url text not null check (url ~* '^https?://'),
  display_mode text not null default 'IFRAME' check (display_mode in ('IFRAME', 'EXTERNAL')),
  sort_order integer not null default 0 check (sort_order between 0 and 10000),
  active boolean not null default true,
  created_by_profile_id bigint references public.profiles(id) on delete set null,
  updated_by_profile_id bigint references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

