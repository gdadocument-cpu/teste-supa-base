create or replace function app_private.publish_gda_roster_planifie()
returns bigint
language plpgsql
set search_path = ''
as $function$
declare
  v_maintenant timestamptz := clock_timestamp();
  v_maintenant_paris timestamp := timezone('Europe/Paris', v_maintenant);
  v_heure_publication time := time '20:00:00';
  v_version_id bigint;
begin
  select configuration.roster_publish_time
  into v_heure_publication
  from public.site_configuration as configuration
  where configuration.singleton = true;

  if to_char(v_maintenant_paris, 'HH24:MI') <> to_char(v_heure_publication, 'HH24:MI') then
    return null;
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('gda_roster_daily_europe_paris', 0)
  );

  select version.id
  into v_version_id
  from public.gda_roster_versions as version
  where timezone('Europe/Paris', version.published_at)::date = v_maintenant_paris::date
    and timezone('Europe/Paris', version.published_at)::time >= v_heure_publication
  order by version.published_at desc, version.id desc
  limit 1;

  if v_version_id is not null then
    return v_version_id;
  end if;

  return app_private.publish_gda_roster_snapshot(
    'Actualisation automatique quotidienne à ' || to_char(v_heure_publication, 'HH24:MI'),
    null
  );
end;
$function$;

revoke all on function app_private.publish_gda_roster_planifie()
  from public, anon, authenticated, service_role;

do $block$
declare
  v_job record;
begin
  for v_job in
    select jobid
    from cron.job
    where jobname in ('publier-effectif-gda-20h-paris', 'publier-effectif-gda-planifie-paris')
  loop
    perform cron.unschedule(v_job.jobid);
  end loop;
end;
$block$;

select cron.schedule(
  'publier-effectif-gda-planifie-paris',
  '* * * * *',
  $cron$select app_private.publish_gda_roster_planifie();$cron$
);
